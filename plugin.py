"""Plugin Foundry — Hermes plugin entry points."""
from __future__ import annotations

from pathlib import Path

try:
    from . import foundry_core as core
except ImportError:
    import foundry_core as core

TOOL_SCHEMAS = [
    {
        "name": "foundry_plan",
        "description": "Parse a plugin request into a narrow spec without writing files.",
        "parameters": {
            "type": "object",
            "properties": {"request": {"type": "string", "minLength": 3}},
            "required": ["request"],
            "additionalProperties": False,
        },
    },
    {
        "name": "foundry_build",
        "description": "Generate a native Hermes plugin from a request, run its tests, and optionally install it.",
        "parameters": {
            "type": "object",
            "properties": {
                "request": {"type": "string", "minLength": 3},
                "output_dir": {"type": "string"},
                "install": {"type": "boolean", "default": False},
            },
            "required": ["request"],
            "additionalProperties": False,
        },
    },
    {
        "name": "foundry_test",
        "description": "Run the generated plugin's tests in its own directory.",
        "parameters": {
            "type": "object",
            "properties": {"path": {"type": "string", "minLength": 1}},
            "required": ["path"],
            "additionalProperties": False,
        },
    },
    {
        "name": "foundry_list",
        "description": "List plugins generated by this Foundry install.",
        "parameters": {"type": "object", "properties": {}, "additionalProperties": False},
    },
    {
        "name": "foundry_catalog",
        "description": "Read the generated catalog draft for a plugin directory.",
        "parameters": {
            "type": "object",
            "properties": {"path": {"type": "string", "minLength": 1}},
            "required": ["path"],
            "additionalProperties": False,
        },
    },
]


def _handler(name: str):
    def call(**kwargs):
        if name == "foundry_plan":
            return core.parse_request(kwargs["request"])
        if name == "foundry_build":
            result = core.build_and_test(
                kwargs["request"],
                output_dir=kwargs.get("output_dir"),
            )
            if kwargs.get("install"):
                spec = result["build"]["spec"]
                result["installed_to"] = core.install_plugin(spec["path"], spec["slug"])
            return result
        if name == "foundry_test":
            return core.run_tests(kwargs["path"])
        if name == "foundry_list":
            return {"plugins": core.list_generated()}
        if name == "foundry_catalog":
            path = Path(kwargs["path"]).expanduser() / "CATALOG.md"
            if not path.exists():
                return {"ok": False, "error": f"no catalog draft at {path}"}
            return {"ok": True, "path": str(path), "content": path.read_text(encoding="utf-8")}
        raise ValueError(f"unknown Foundry tool: {name}")
    return call


def register(ctx):
    for schema in TOOL_SCHEMAS:
        ctx.register_tool(name=schema["name"], toolset="plugin_foundry",
                          schema=schema, handler=_handler(schema["name"]))
